import AppKit
import SaveNestCore

@MainActor
final class ClipboardMonitor {
    private var timer: Timer?
    private var changeCount = 0
    var onLink: ((URL) -> Void)?
    func start() {
        stop()
        // Enabling never inspects clipboard contents copied before consent.
        changeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.check() }
        }
    }
    func stop() { timer?.invalidate(); timer = nil }
    private func check() {
        let board = NSPasteboard.general
        guard board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !privateTypes.contains(where: { board.types?.contains(NSPasteboard.PasteboardType($0)) == true }),
              let text = board.string(forType: .string), let url = ClipboardLink.parse(text) else { return }
        onLink?(url)
    }
    deinit { timer?.invalidate() }
}
