import Foundation
import SaveNestCore

func runNoteFileChecks() throws {
    let manager = FileManager.default
    let root = manager.temporaryDirectory.resolvingSymlinksInPath().appendingPathComponent("SaveNest-note-checks-\(UUID().uuidString)")
    defer { try? manager.removeItem(at: root) }
    let vault = root.appendingPathComponent("Vault")
    let settings = vault.appendingPathComponent(".obsidian")
    try manager.createDirectory(at: settings, withIntermediateDirectories: true)
    try Data(#"{"newFileLocation":"folder","newFileFolderPath":"1 - Rough notes"}"#.utf8).write(to: settings.appendingPathComponent("app.json"))
    let service = try NoteFiles(storage: root.appendingPathComponent("Private"))
    XCTAssertThrowsError(try service.load(url: "https://example.com", title: "A page"))
    try service.configure(vault: vault)
    XCTAssertEqual(service.configuration?.folder, "1 - Rough notes")
    let initial = try service.load(url: "https://Example.com/", title: "A / useful: page")
    let id = initial["documentId"] as! String
    XCTAssertFalse(initial["exists"] as! Bool)
    XCTAssertFalse(manager.fileExists(atPath: initial["path"] as! String))
    try XCTAssertEqual((try service.load(url: "https://example.com", title: "Other title"))["documentId"] as? String, id)
    let text = (initial["text"] as! String) + "A thought with **emphasis** and [[a link]].\n"
    let saved = try service.save(id: id, text: text, revision: "missing")
    XCTAssertTrue(saved["exists"] as! Bool)
    let file = URL(fileURLWithPath: saved["path"] as! String)
    try XCTAssertEqual(try String(contentsOf: file, encoding: .utf8), text)
    let revision = saved["revision"] as! String
    try Data((text + "External edit\n").utf8).write(to: file, options: .atomic)
    let conflict = try service.save(id: id, text: text + "My edit\n", revision: revision)
    XCTAssertTrue(conflict["conflict"] as! Bool)
    try XCTAssertEqual(try String(contentsOf: file, encoding: .utf8), text + "External edit\n")
    let reopened = try NoteFiles(storage: root.appendingPathComponent("Private"))
    let recovery = try reopened.load(url: "https://example.com", title: "Ignored")
    XCTAssertTrue(recovery["recovered"] as! Bool)
    XCTAssertTrue(recovery["conflict"] as! Bool)
    XCTAssertEqual(recovery["text"] as? String, text + "My edit\n")
    let literalBody = "\n```yaml\nsavenest_id: \"\(id)\"\n```\n"
    let copy = try reopened.saveCopy(id: id, text: text + "My edit\n" + literalBody)
    XCTAssertTrue(copy["exists"] as! Bool)
    XCTAssertFalse(copy["path"] as! String == file.path)
    XCTAssertTrue((copy["text"] as! String).contains(literalBody))
    XCTAssertTrue((copy["text"] as! String).hasPrefix("---\nsavenest_id: \"\(copy["documentId"] as! String)\"\n"))
    try XCTAssertEqual(try String(contentsOf: file, encoding: .utf8), text + "External edit\n")
    try XCTAssertEqual((try reopened.load(url: "https://example.com", title: "Ignored"))["documentId"] as? String, copy["documentId"] as? String)
    let collision = try reopened.load(url: "https://example.com/second", title: "A / useful: page")
    XCTAssertFalse(collision["path"] as! String == file.path)
    XCTAssertThrowsError(try reopened.configure(vault: vault, folder: "../escape"))
    XCTAssertThrowsError(try reopened.configure(vault: vault, folder: ".obsidian"))
    let outside = root.appendingPathComponent("Outside")
    try manager.createDirectory(at: outside, withIntermediateDirectories: true)
    try manager.createSymbolicLink(at: vault.appendingPathComponent("Escape"), withDestinationURL: outside)
    XCTAssertThrowsError(try reopened.configure(vault: vault, folder: "Escape"))
    let currentID = copy["documentId"] as! String
    let copyURL = URL(fileURLWithPath: copy["path"] as! String)
    let moved = copyURL.deletingLastPathComponent().appendingPathComponent("Renamed in Obsidian.md")
    try manager.moveItem(at: copyURL, to: moved)
    XCTAssertTrue((try reopened.check(id: currentID, revision: copy["revision"] as! String))["missing"] as! Bool)
    let located = try reopened.locate(id: currentID, file: moved)
    XCTAssertEqual(located["path"] as? String, moved.path)
    // Invalid or oversized external files must never be replaced by an editor save.
    let originalBytes = try Data(contentsOf: moved)
    try Data([0xff, 0xfe, 0x00]).write(to: moved, options: .atomic)
    XCTAssertThrowsError(try reopened.check(id: currentID, revision: "missing"))
    XCTAssertThrowsError(try reopened.save(id: currentID, text: "Do not overwrite", revision: located["revision"] as! String))
    try XCTAssertEqual(try Data(contentsOf: moved), Data([0xff, 0xfe, 0x00]))
    let oversized = Data(repeating: 65, count: NoteFiles.maximumCharacters * 4 + 1)
    try oversized.write(to: moved, options: .atomic)
    XCTAssertThrowsError(try reopened.check(id: currentID, revision: "missing"))
    try XCTAssertEqual(try Data(contentsOf: moved), oversized)
    try originalBytes.write(to: moved, options: .atomic)
    try reopened.discardDraft(id: currentID)
    // A deleted, previously saved note must not be silently recreated.
    try manager.removeItem(at: moved)
    XCTAssertThrowsError(try reopened.save(id: currentID, text: "Keep this draft", revision: "missing"))
    XCTAssertFalse(manager.fileExists(atPath: moved.path))
    let deletedRecovery = try reopened.load(url: "https://example.com", title: "Ignored")
    XCTAssertEqual(deletedRecovery["text"] as? String, "Keep this draft")
    XCTAssertTrue(deletedRecovery["recovered"] as! Bool)
    try originalBytes.write(to: moved, options: .atomic)
    try reopened.discardDraft(id: currentID)
    // A second vault only changes where new notes are made.
    let other = root.appendingPathComponent("Second vault")
    try manager.createDirectory(at: other.appendingPathComponent(".obsidian"), withIntermediateDirectories: true)
    try reopened.configure(vault: other)
    try XCTAssertEqual((try reopened.load(url: "https://example.com", title: "Ignored"))["path"] as? String, moved.path)
    XCTAssertTrue((try reopened.load(url: "https://example.com/new", title: "New"))["path"] as! String == other.appendingPathComponent("SaveNest/New.md").path)
    // Removing a vault must not recreate its folder tree during save.
    let pending = try reopened.load(url: "https://example.com/pending", title: "Pending")
    try manager.removeItem(at: other)
    XCTAssertThrowsError(try reopened.save(id: pending["documentId"] as! String, text: "pending", revision: "missing"))
    XCTAssertFalse(manager.fileExists(atPath: other.path))
    print("Passed Markdown note file, conflict, recovery, and vault-boundary checks")
}
